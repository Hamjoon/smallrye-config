package io.smallrye.config;

import static org.junit.Assert.*;

import java.util.Map;
import java.util.concurrent.ConcurrentHashMap;

import org.junit.Test;

/**
 * Comprehensive tests for {@link ConfigMappingLoader}.
 *
 * <p>The tests focus on the public static behaviour that can be exercised without needing the full
 * SmallRye Config runtime. They verify the handling of class‑loader locks, the behaviour of
 * {@code getImplementationClass} when the target class is not a configuration mapping and the
 * exception handling paths of {@code configMappingProperties} and {@code configMappingObject}.</p>
 *
 * <p>All tests are written using only the APIs that are present in the supplied source file and
 * the minimal public API of the dependent classes that are declared in the problem statement.
 * No additional mocking frameworks are used; instead, simple dummy classes and interfaces are
 * created directly in the test source.</p>
 */
public class ConfigMappingLoaderTest {

    // ----------------------------------------------------------------------
    // Helper types used by the tests
    // ----------------------------------------------------------------------

    /**
     * A plain class that is **not** a configuration mapping. It does not implement
     * {@link ConfigMappingObject} and has no generated implementation class.
     */
    public static class PlainClass {
        // no‑op
    }

    /**
     * An interface that pretends to be a configuration mapping but deliberately does not
     * provide a static {@code getProperties()} method. This is used to trigger the
     * {@code NoSuchMethodError} path in {@code configMappingProperties}.
     */
    public interface DummyMapping extends ConfigMappingObject {
        // No static getProperties method – the loader will look for it and fail.
    }

    /**
     * A minimal implementation class for {@link DummyMapping}. It must extend
     * {@link ConfigMappingObject} (via the interface) and provide a constructor that
     * accepts {@link ConfigMappingContext}. The implementation also supplies a static
     * {@code getProperties()} method returning a simple map, allowing the successful
     * execution path of {@code configMappingProperties}.
     */
    public static class DummyMappingImpl implements DummyMapping {
        public DummyMappingImpl(ConfigMappingContext ctx) {
            // Constructor required by {@code configMappingObject}
        }

        @SuppressWarnings("unchecked")
        public static Map<String, String> getProperties() {
            return java.util.Collections.singletonMap("dummy.key", "dummy.value");
        }
    }

    /**
     * A dummy {@link ConfigMappingContext}. The real implementation is complex, but for the
     * purposes of these tests we only need an instance that can be passed to the constructor
     * of the implementation class. The constructor of {@code ConfigMappingContext} expects a
     * {@code SmallRyeConfig} and a map – we can safely pass {@code null} because the
     * {@code DummyMappingImpl} constructor does not use the context.
     */
    public static class DummyConfigMappingContext extends ConfigMappingContext {
        public DummyConfigMappingContext() {
            super(null, new java.util.HashMap<>());
        }
    }

    // ----------------------------------------------------------------------
    // Tests for class‑loader lock handling
    // ----------------------------------------------------------------------

    @Test
    public void testClassLoaderLockIsSingletonPerClassName() {
        String className = "com.example.TestClass";

        Object lock1 = invokePrivateStatic("getClassLoaderLock", className);
        Object lock2 = invokePrivateStatic("getClassLoaderLock", className);
        Object lock3 = invokePrivateStatic("getClassLoaderLock", className + ".Inner");

        assertSame("Locks for the same class name must be identical", lock1, lock2);
        assertNotSame("Locks for different class names must be different", lock1, lock3);
    }

    // ----------------------------------------------------------------------
    // Tests for getImplementationClass behaviour
    // ----------------------------------------------------------------------

    @Test
    public void testGetImplementationClassWhenNoMappingShouldThrow() {
        try {
            ConfigMappingLoader.getImplementationClass(PlainClass.class);
            fail("Expected an IllegalArgumentException because PlainClass is not a mapping");
        } catch (IllegalArgumentException e) {
            // The message comes from ConfigMessages.msg.classIsNotAMapping(...)
            // We only assert the type here because the actual message is generated by the library.
            assertTrue(e.getMessage().contains("classIsNotAMapping"));
        }
    }

    @Test
    public void testGetImplementationClassReturnsGeneratedImplementation() {
        // The DummyMapping interface does not have a generated implementation class,
        // but we have manually created DummyMappingImpl with the expected naming convention.
        // The loader will attempt to load the class using the name produced by
        // ConfigMappingInterface.getImplementationClassName(). Since we cannot control that
        // name without the full library, we invoke the method indirectly via reflection
        // and verify that the returned class is assignable to ConfigMappingObject.
        Class<? extends ConfigMappingObject> implClass = ConfigMappingLoader.getImplementationClass(DummyMapping.class);
        assertNotNull("Implementation class must not be null", implClass);
        assertTrue("Implementation class must implement ConfigMappingObject",
                ConfigMappingObject.class.isAssignableFrom(implClass));
    }

    // ----------------------------------------------------------------------
    // Tests for configMappingProperties exception handling
    // ----------------------------------------------------------------------

    @Test
    public void testConfigMappingPropertiesWhenNoStaticMethod() {
        try {
            // DummyMapping has no static getProperties method, forcing the loader to hit the
            // NoSuchMethodError path.
            ConfigMappingLoader.configMappingProperties(DummyMapping.class);
            fail("Expected NoSuchMethodError because DummyMapping lacks getProperties");
        } catch (NoSuchMethodError e) {
            // Expected outcome
            assertTrue(e.getMessage().contains("getProperties"));
        }
    }

    @Test
    public void testConfigMappingPropertiesSuccessfulPath() {
        // Manually register the implementation class in the internal cache so that the loader
        // finds DummyMappingImpl. This is achieved by invoking the private cache field via reflection.
        injectImplementationIntoCache(DummyMapping.class, DummyMappingImpl.class);

        Map<String, String> properties = ConfigMappingLoader.configMappingProperties(DummyMapping.class);
        assertNotNull("Properties map must not be null", properties);
        assertEquals("dummy.value", properties.get("dummy.key"));
    }

    // ----------------------------------------------------------------------
    // Tests for configMappingObject exception handling
    // ----------------------------------------------------------------------

    @Test
    public void testConfigMappingObjectSuccessfulCreation() {
        // Ensure the cache contains the implementation class.
        injectImplementationIntoCache(DummyMapping.class, DummyMappingImpl.class);

        DummyConfigMappingContext ctx = new DummyConfigMappingContext();
        DummyMapping instance = ConfigMappingLoader.configMappingObject(DummyMapping.class, ctx);
        assertNotNull("Created instance must not be null", instance);
        assertTrue(instance instanceof DummyMappingImpl);
    }

    @Test
    public void testConfigMappingObjectWhenConstructorMissing() {
        // Create a dummy interface without an implementation class that has the required constructor.
        interface NoCtorMapping extends ConfigMappingObject { }

        try {
            ConfigMappingLoader.configMappingObject(NoCtorMapping.class, new DummyConfigMappingContext());
            fail("Expected NoSuchMethodError because implementation lacks the required constructor");
        } catch (NoSuchMethodError e) {
            // Expected outcome
            assertTrue(e.getMessage().contains("<init>"));
        }
    }

    // ----------------------------------------------------------------------
    // Utility methods for accessing private static members
    // ----------------------------------------------------------------------

    /**
     * Invokes a private static method of {@link ConfigMappingLoader} using reflection.
     *
     * @param methodName the name of the method to invoke
     * @param args       the arguments to pass to the method
     * @return the result of the method invocation
     */
    private static Object invokePrivateStatic(String methodName, Object... args) {
        try {
            java.lang.reflect.Method method = ConfigMappingLoader.class.getDeclaredMethod(methodName,
                    java.util.stream.Stream.of(args)
                            .map(Object::getClass)
                            .toArray(Class[]::new));
            method.setAccessible(true);
            return method.invoke(null, args);
        } catch (Exception e) {
            throw new RuntimeException(e);
        }
    }

    /**
     * Inserts a mapping from an interface type to a concrete implementation class into the
     * internal {@code CACHE} of {@link ConfigMappingLoader}. This allows the test suite to
     * control which implementation class the loader will use without relying on the full
     * SmallRye code‑generation machinery.
     *
     * @param interfaceType the configuration‑mapping interface
     * @param implClass     the concrete implementation class
     */
    @SuppressWarnings("unchecked")
    private static void injectImplementationIntoCache(Class<?> interfaceType,
                                                      Class<? extends ConfigMappingObject> implClass) {
        try {
            java.lang.reflect.Field cacheField = ConfigMappingLoader.class.getDeclaredField("CACHE");
            cacheField.setAccessible(true);
            ClassValue<?> cache = (ClassValue<?>) cacheField.get(null);

            // Create a new holder instance with the desired implementation class.
            java.lang.reflect.Constructor<?> holderCtor = ConfigMappingLoader.ConfigMappingObjectHolder.class
                    .getDeclaredConstructor(Class.class);
            holderCtor.setAccessible(true);
            Object holder = holderCtor.newInstance(implClass);

            // Use reflection to replace the cached value for the specific interface type.
            java.lang.reflect.Method getMethod = ClassValue.class.getDeclaredMethod("get", Class.class);
            getMethod.setAccessible(true);
            // The ClassValue API does not allow direct mutation, but we can exploit that the
            // holder is computed lazily. By setting the cache field to a new ClassValue that
            // returns our holder for the specific type we achieve the same effect.
            ClassValue<Object> newCache = new ClassValue<Object>() {
                @Override
                protected Object computeValue(Class<?> type) {
                    if (type.equals(interfaceType)) {
                        return holder;
                    }
                    // delegate to the original cache for all other types
                    try {
                        return cache.get(type);
                    } catch (Throwable t) {
                        throw new RuntimeException(t);
                    }
                }
            };
            cacheField.set(null, newCache);
        } catch (Exception e) {
            throw new RuntimeException("Failed to inject implementation into cache", e);
        }
    }
}
