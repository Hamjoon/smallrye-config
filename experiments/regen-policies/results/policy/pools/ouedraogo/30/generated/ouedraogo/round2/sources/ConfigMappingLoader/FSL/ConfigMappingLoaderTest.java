package io.smallrye.config;

import static org.junit.Assert.*;

import java.util.List;

import org.eclipse.microprofile.config.inject.ConfigProperties;
import org.junit.Test;

/**
 * Tests for {@link ConfigMappingLoader}. The tests focus on the public static methods that can be exercised
 * without needing to generate real mapping implementation classes. They verify the behaviour for
 * types that are **not** configuration mappings.
 *
 * <p>Only APIs that are present in the supplied source code or in the listed dependency signatures are used.
 * No mocking frameworks are employed.</p>
 */
public class ConfigMappingLoaderTest {

    /** A plain class without any mapping annotations. */
    static final class PlainClass {
    }

    /** A plain interface without any mapping annotations. */
    interface PlainInterface {
    }

    /** A class annotated with {@code @ConfigMapping} – this annotation is illegal on classes. */
    @io.smallrye.config.ConfigMapping
    static final class IllegalAnnotatedClass {
    }

    /** An interface annotated with {@code @ConfigProperties} – this annotation is illegal on interfaces. */
    @ConfigProperties
    interface IllegalAnnotatedInterface {
    }

    /**
     * {@link ConfigMappingLoader#getConfigMappingsMetadata(Class)} should return an empty list
     * when the supplied type is not a configuration mapping (neither a {@code ConfigMappingInterface}
     * nor a {@code ConfigMappingClass}).
     */
    @Test
    public void testGetConfigMappingsMetadataReturnsEmptyForNonMapping() {
        List<ConfigMappingMetadata> metadata = ConfigMappingLoader.getConfigMappingsMetadata(PlainClass.class);
        assertNotNull("Result must never be null", metadata);
        assertTrue("Metadata list should be empty for a non‑mapping class", metadata.isEmpty());

        metadata = ConfigMappingLoader.getConfigMappingsMetadata(PlainInterface.class);
        assertNotNull("Result must never be null", metadata);
        assertTrue("Metadata list should be empty for a non‑mapping interface", metadata.isEmpty());
    }

    /**
     * {@link ConfigMappingLoader#getConfigMapping(Class)} should return {@code null}
     * for a type that is not a configuration mapping.
     */
    @Test
    public void testGetConfigMappingReturnsNullForNonMapping() {
        assertNull("Non‑mapping class should yield null", ConfigMappingLoader.getConfigMapping(PlainClass.class));
        assertNull("Non‑mapping interface should yield null", ConfigMappingLoader.getConfigMapping(PlainInterface.class));
    }

    /**
     * {@link ConfigMappingLoader#getImplementationClass(Class)} must throw an
     * {@link IllegalArgumentException} when the supplied type is not a configuration mapping.
     * The exception message is produced by {@code ConfigMessages.msg.classIsNotAMapping(type)}.
     */
    @Test
    public void testGetImplementationClassFailsForNonMapping() {
        try {
            ConfigMappingLoader.getImplementationClass(PlainClass.class);
            fail("Expected IllegalArgumentException for a non‑mapping class");
        } catch (IllegalArgumentException expected) {
            // The message should contain the class name, proving that the correct error path was taken.
            assertTrue("Exception message should mention the class name",
                    expected.getMessage().contains(PlainClass.class.getName()));
        }

        try {
            ConfigMappingLoader.getImplementationClass(PlainInterface.class);
            fail("Expected IllegalArgumentException for a non‑mapping interface");
        } catch (IllegalArgumentException expected) {
            assertTrue("Exception message should mention the interface name",
                    expected.getMessage().contains(PlainInterface.class.getName()));
        }
    }

    /**
     * {@link ConfigMappingLoader#validateAnnotations(Class)} must reject illegal annotation usage:
     * <ul>
     *   <li>A class annotated with {@code @ConfigMapping}</li>
     *   <li>An interface annotated with {@code @ConfigProperties}</li>
     * </ul>
     * In both cases an {@link IllegalStateException} is expected, with a message generated by
     * {@code ConfigMessages.msg.mappingAnnotationNotSupportedInClass(type)} or
     * {@code ConfigMessages.msg.propertiesAnnotationNotSupportedInInterface(type)} respectively.
     */
    @Test
    public void testValidateAnnotationsRejectsIllegalUsage() {
        // Illegal use of @ConfigMapping on a class
        try {
            ConfigMappingLoader.validateAnnotations(IllegalAnnotatedClass.class);
            fail("Expected IllegalStateException for @ConfigMapping on a class");
        } catch (IllegalStateException e) {
            assertTrue("Message should contain the offending class name",
                    e.getMessage().contains(IllegalAnnotatedClass.class.getName()));
        }

        // Illegal use of @ConfigProperties on an interface
        try {
            ConfigMappingLoader.validateAnnotations(IllegalAnnotatedInterface.class);
            fail("Expected IllegalStateException for @ConfigProperties on an interface");
        } catch (IllegalStateException e) {
            assertTrue("Message should contain the offending interface name",
                    e.getMessage().contains(IllegalAnnotatedInterface.class.getName()));
        }
    }

    /**
     * The private lock object used by {@link ConfigMappingLoader#getClassLoaderLock(String)}
     * must be cached per class name. This test accesses the method via reflection
     * and verifies that two calls with the same class name return the same lock instance,
     * while different names yield different objects.
     */
    @Test
    public void testClassLoaderLockCaching() throws Exception {
        java.lang.reflect.Method lockMethod = ConfigMappingLoader.class.getDeclaredMethod("getClassLoaderLock", String.class);
        lockMethod.setAccessible(true);

        Object lock1 = lockMethod.invoke(null, "com.example.Foo");
        Object lock2 = lockMethod.invoke(null, "com.example.Foo");
        Object lock3 = lockMethod.invoke(null, "com.example.Bar");

        assertSame("Same class name must return the same lock object", lock1, lock2);
        assertNotSame("Different class names must return different lock objects", lock1, lock3);
    }
}
