package io.smallrye.config;

import static org.junit.jupiter.api.Assertions.*;
// @ExtendWith(MockitoExtension.class)
import org.junit.jupiter.api.Test;

// optional removal; can be omitted entirely
class ConfigMappingInterface_getConfigurationInterface_Test {

    @ConfigMapping(prefix = "dummy")
    interface DummyConfig {

        String name();
    }

    @ConfigMapping(prefix = "valid")
    interface ValidConfig {

        String name();
    }

    // No @ConfigMapping annotation – should be rejected
    interface NoAnnotationInterface {

        String foo();
    }

    @ConfigMapping(prefix = "parent")
    interface ParentConfigInterface {

        String parentProp();
    }

    @ConfigMapping(prefix = "child")
    interface ChildConfigInterface extends ParentConfigInterface {

        String childProp();
    }

    @ConfigMapping(prefix = "generic")
    interface GenericConfigInterface {

        <T> T get(String key);
    }

    @ConfigMapping(prefix = "bean")
    interface BeanStyleInterface {

        String getName();

        String getAge();
    }

    @ConfigMapping(prefix = "conflict")
    interface ConflictingMethodsInterface {

        // maps to key "foo"
        String foo();

        // also maps to key "foo" → conflict
        String getFoo();
    }

    @ConfigMapping(prefix = "unsupported")
    interface UnsupportedSignatureInterface {

        // More than one parameter – not supported by the mapping processor
        String invalid(String p1, int p2);
    }

    @ConfigMapping(prefix = "a")
    interface ConfigInterfaceA {

        String a();
    }

    @ConfigMapping(prefix = "b")
    interface ConfigInterfaceB {

        String b();
    }

    @Test
    void getConfigurationInterface_returnsMetadataAndCachesResult() {
        // GIVEN – a simple @ConfigMapping interface
        Class<?> iface = DummyConfig.class;
        // WHEN – the configuration interface is obtained for the first time
        ConfigMappingInterface first = ConfigMappingInterface.getConfigurationInterface(iface);
        // THEN – a non‑null metadata object is returned and it reflects the original interface
        assertNotNull(first, "The returned ConfigMappingInterface must not be null");
        assertEquals(iface, first.getInterfaceType(), "The metadata should report the original interface type");
        // WHEN – the same call is performed again
        ConfigMappingInterface second = ConfigMappingInterface.getConfigurationInterface(iface);
        // THEN – the cached instance is returned (identity equality)
        assertSame(first, second, "Subsequent calls must return the same cached instance");
    }

    @Test
    void getConfigurationInterface_nullArgumentThrows() {
        // GIVEN – a null argument
        // WHEN / THEN – an IllegalArgumentException (generated by Assert.checkNotNullParam) is thrown
        assertThrows(IllegalArgumentException.class, () -> ConfigMappingInterface.getConfigurationInterface(null), "Calling getConfigurationInterface with null must fail fast");
    }

    /**
     * A properly annotated interface returns a non‑null metadata object.
     */
    @Test
    void getConfigurationInterface_validInterface_returnsMetadata() {
        ConfigMappingInterface meta = ConfigMappingInterface.getConfigurationInterface(ValidConfig.class);
        assertNotNull(meta, "Metadata must not be null for a valid @ConfigMapping interface");
        assertEquals(ValidConfig.class, meta.getInterfaceType(), "The metadata should report the original interface type");
    }

    /**
     * Non‑interface classes (e.g. {@link String}) are rejected.
     */
    @Test
    void getConfigurationInterface_nonInterfaceClassThrows() {
        assertThrows(IllegalArgumentException.class, () -> ConfigMappingInterface.getConfigurationInterface(String.class), "Supplying a concrete class should result in an IllegalArgumentException");
    }

    /**
     * Interfaces lacking the {@code @ConfigMapping} annotation are rejected.
     */
    @Test
    void getConfigurationInterface_missingAnnotationThrows() {
        assertThrows(IllegalArgumentException.class, () -> ConfigMappingInterface.getConfigurationInterface(NoAnnotationInterface.class), "Interface without @ConfigMapping should be rejected");
    }

    /**
     * Inheritance between configuration interfaces must be reflected in super‑type metadata.
     */
    @Test
    void getConfigurationInterface_interfaceExtendsAnother_returnsSuperTypes() {
        ConfigMappingInterface childMeta = ConfigMappingInterface.getConfigurationInterface(ChildConfigInterface.class);
        assertNotNull(childMeta, "Child metadata must not be null");
        ConfigMappingInterface[] supers = childMeta.getSuperTypes();
        assertNotNull(supers, "Super types array must not be null");
        assertTrue(supers.length > 0, "There should be at least one super type");
        boolean foundParent = false;
        for (ConfigMappingInterface sup : supers) {
            if (sup.getInterfaceType() == ParentConfigInterface.class) {
                foundParent = true;
                break;
            }
        }
        assertTrue(foundParent, "Super types must contain metadata for ParentConfigInterface");
    }

    /**
     * Interfaces that declare generic methods are still processed successfully.
     */
    @Test
    void getConfigurationInterface_genericInterface_returnsMetadata() {
        ConfigMappingInterface meta = ConfigMappingInterface.getConfigurationInterface(GenericConfigInterface.class);
        assertNotNull(meta, "Metadata must be created for an interface with generic methods");
        assertEquals(GenericConfigInterface.class, meta.getInterfaceType(), "Interface type must be preserved");
    }

    /**
     * Bean‑style getter detection – {@code isBeanStyleGetters()} must be true.
     */
    @Test
    void getConfigurationInterface_beanStyleGetters_detected() {
        ConfigMappingInterface meta = ConfigMappingInterface.getConfigurationInterface(BeanStyleInterface.class);
        assertNotNull(meta, "Metadata must be created for bean‑style interface");
        assertTrue(meta.isBeanStyleGetters(), "Interface that follows bean‑style getters should be marked as such");
    }

    /**
     * Conflicting method names (e.g. {@code foo()} and {@code getFoo()}) must cause an exception.
     */
    @Test
    void getConfigurationInterface_conflictingMethodsThrows() {
        assertThrows(IllegalArgumentException.class, () -> ConfigMappingInterface.getConfigurationInterface(ConflictingMethodsInterface.class), "Conflicting method names should trigger an IllegalArgumentException");
    }

    /**
     * Unsupported method signatures (e.g. more than one parameter) must cause an exception.
     */
    @Test
    void getConfigurationInterface_unsupportedSignatureThrows() {
        assertThrows(IllegalArgumentException.class, () -> ConfigMappingInterface.getConfigurationInterface(UnsupportedSignatureInterface.class), "Methods with unsupported signatures must trigger an IllegalArgumentException");
    }

    /**
     * Repeated calls with the same interface must return the cached instance (identity equality).
     */
    @Test
    void getConfigurationInterface_cachingSameInstance() {
        ConfigMappingInterface first = ConfigMappingInterface.getConfigurationInterface(ValidConfig.class);
        ConfigMappingInterface second = ConfigMappingInterface.getConfigurationInterface(ValidConfig.class);
        assertSame(first, second, "Subsequent calls must return the same cached instance");
    }

    /**
     * Calls with different interfaces must produce distinct metadata objects.
     */
    @Test
    void getConfigurationInterface_differentInterfacesProduceDistinctInstances() {
        ConfigMappingInterface metaA = ConfigMappingInterface.getConfigurationInterface(ConfigInterfaceA.class);
        ConfigMappingInterface metaB = ConfigMappingInterface.getConfigurationInterface(ConfigInterfaceB.class);
        assertNotNull(metaA);
        assertNotNull(metaB);
        assertNotSame(metaA, metaB, "Different interfaces must result in different ConfigMappingInterface instances");
    }
}
