package io.smallrye.config;

import static org.junit.jupiter.api.Assertions.*;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.MethodSource;
import java.util.stream.Stream;
import org.junit.jupiter.params.provider.Arguments;

class ConfigMappingInterface_getClassName_Test {

    // Simple configuration interface used only for the test
    interface SampleConfig {
        // no methods needed
    }

    /**
     * Simple configuration interface – no inheritance.
     */
    interface SimpleConfig {
        // No methods required for the test
    }

    /**
     * Parent interface – could also be a configuration interface.
     */
    interface ParentConfig {
        // No methods required for the test
    }

    /**
     * Child interface that inherits from {@link ParentConfig}.
     */
    interface ChildConfig extends ParentConfig {
        // No methods required for the test
    }

    /**
     * Supplies test arguments: the configuration interface class and a short description.
     */
    static Stream<org.junit.jupiter.params.provider.Arguments> interfaceProvider() {
        return Stream.of(Arguments.of(SimpleConfig.class, "Simple configuration interface"), Arguments.of(ChildConfig.class, "Configuration interface that extends another interface"));
    }

    /**
     * Verifies that {@link ConfigMappingInterface#getClassName()} returns the same value
     * as the static helper {@link ConfigMappingInterface#getImplementationClassName(Class)}.
     *
     * @param ifaceClass   the configuration interface to test
     * @param description  a short description used only for the test name
     */
    @ParameterizedTest(name = "{1}")
    @MethodSource("interfaceProvider")
    void getClassNameReturnsImplementationClassName(Class<?> ifaceClass, String description) {
        // Arrange – create a ConfigMappingInterface instance for the given iface
        ConfigMappingInterface configMapping = new ConfigMappingInterface(ifaceClass, ConfigMappingInterface.NO_TYPES, new ConfigMappingInterface.Property[0]);
        // Act – obtain the class name from the instance
        String actualClassName = configMapping.getClassName();
        // Expected – generated by the library's static helper
        String expectedClassName = ConfigMappingInterface.getImplementationClassName(ifaceClass);
        // Assert – the two names must be equal and not null
        assertNotNull(actualClassName, () -> "className should not be null for interface: " + ifaceClass.getName());
        assertEquals(expectedClassName, actualClassName, () -> "ConfigMappingInterface#getClassName should return the implementation class name generated for interface: " + ifaceClass.getName());
    }
}
