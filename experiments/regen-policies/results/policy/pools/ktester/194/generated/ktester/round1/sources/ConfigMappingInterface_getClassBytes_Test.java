package io.smallrye.config;

import static org.junit.jupiter.api.Assertions.*;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

@ExtendWith(MockitoExtension.class)
class ConfigMappingInterface_getClassBytes_Test {

    private ConfigMappingInterface configMappingInterface;

    // ----------------------------------------------------------------------
    @ConfigMapping(prefix = "dummy")
    interface DummyConfig {
        // No methods – the interface exists solely to provide a Class<?> for the constructor.
    }

    @BeforeEach
    void setupBeforeEach() {
        // Create a minimal ConfigMappingInterface instance.
        // The constructor is package‑private, but the test resides in the same package,
        // so it can be accessed directly.
        Class<?> dummyInterface = DummyConfig.class;
        ConfigMappingInterface[] superTypes = ConfigMappingInterface.NO_TYPES;
        ConfigMappingInterface.Property[] properties = ConfigMappingInterface.NO_PROPERTIES;
        configMappingInterface = new ConfigMappingInterface(dummyInterface, superTypes, properties);
    }

    /**
     * Verify that a successful call to {@code ConfigMappingGenerator.generate}
     * returns the exact byte array produced by {@code getClassBytes()}.
     */
    @Test
    void getClassBytes_returnsGeneratedBytes() {
        byte[] expected = new byte[] { 0x01, 0x02, 0x03 };
        try (MockedStatic<ConfigMappingGenerator> generatorMock = Mockito.mockStatic(ConfigMappingGenerator.class)) {
            generatorMock.when(() -> ConfigMappingGenerator.generate(any())).thenReturn(expected);
            byte[] actual = configMappingInterface.getClassBytes();
            assertArrayEquals(expected, actual, "The returned byte array should match the generated one");
            generatorMock.verify(() -> ConfigMappingGenerator.generate(configMappingInterface));
        }
    }

    /**
     * Verify that when {@code ConfigMappingGenerator.generate} throws an exception,
     * {@code getClassBytes()} wraps it with the appropriate {@link ConfigException}.
     */
    @Test
    void getClassBytes_wrapsGenerationException() {
        RuntimeException cause = new IllegalStateException("generation failed");
        try (MockedStatic<ConfigMappingGenerator> generatorMock = Mockito.mockStatic(ConfigMappingGenerator.class)) {
            generatorMock.when(() -> ConfigMappingGenerator.generate(any())).thenThrow(cause);
            ConfigException thrown = assertThrows(ConfigException.class, () -> configMappingInterface.getClassBytes(), "Expected a ConfigException to be thrown when generation fails");
            // The message should indicate a generation failure.
            assertTrue(thrown.getMessage().toLowerCase().contains("could not generate mapping"), "Exception message should indicate generation failure");
            assertSame(cause, thrown.getCause(), "The original cause should be preserved as the cause of the ConfigException");
        }
    }

    /**
     * Scenario: {@code ConfigMappingGenerator.generate} returns a non‑null byte array.
     * Expectation: the same array is returned by {@code getClassBytes()}.
     */
    @Test
    void getClassBytes_successfulGeneration() {
        byte[] expected = new byte[] { 0x01, 0x02, 0x03 };
        try (MockedStatic<ConfigMappingGenerator> generatorMock = Mockito.mockStatic(ConfigMappingGenerator.class)) {
            generatorMock.when(() -> ConfigMappingGenerator.generate(any())).thenReturn(expected);
            byte[] actual = configMappingInterface.getClassBytes();
            assertArrayEquals(expected, actual, "Returned bytes must match the generated bytes");
            generatorMock.verify(() -> ConfigMappingGenerator.generate(configMappingInterface));
        }
    }

    /**
     * Scenario: {@code ConfigMappingGenerator.generate} throws a {@link RuntimeException}.
     * Expectation: {@code getClassBytes()} re‑throws the exception produced by
     * {@link ConfigMessages#couldNotGenerateMapping(Throwable)} (a {@link ConfigException})
     * and preserves the original cause.
     */
    @Test
    void getClassBytes_generationThrowsRuntimeException() {
        RuntimeException cause = new IllegalStateException("generation failed");
        try (MockedStatic<ConfigMappingGenerator> generatorMock = Mockito.mockStatic(ConfigMappingGenerator.class)) {
            generatorMock.when(() -> ConfigMappingGenerator.generate(any())).thenThrow(cause);
            ConfigException thrown = assertThrows(ConfigException.class, configMappingInterface::getClassBytes, "Expected ConfigException when generation throws RuntimeException");
            assertTrue(thrown.getMessage().toLowerCase().contains("could not generate mapping"), "Exception message should indicate generation failure");
            assertSame(cause, thrown.getCause(), "Original cause must be preserved");
        }
    }

    /**
     * Scenario: {@code ConfigMappingGenerator.generate} throws a checked exception
     * (e.g. {@link IOException}).
     * Expectation: the checked exception is caught as {@link Throwable} and wrapped
     * in a {@link ConfigException} by {@code ConfigMessages}.
     */
    @Test
    void getClassBytes_generationThrowsCheckedException() {
        IOException cause = new IOException("IO error");
        try (MockedStatic<ConfigMappingGenerator> generatorMock = Mockito.mockStatic(ConfigMappingGenerator.class)) {
            generatorMock.when(() -> ConfigMappingGenerator.generate(any())).thenThrow(cause);
            ConfigException thrown = assertThrows(ConfigException.class, configMappingInterface::getClassBytes, "Expected ConfigException when generation throws a checked exception");
            assertTrue(thrown.getMessage().toLowerCase().contains("could not generate mapping"));
            assertSame(cause, thrown.getCause(), "The original IOException should be the cause of the ConfigException");
        }
    }

    /**
     * Scenario: {@code ConfigMappingGenerator.generate} throws an {@link Error}
     * (e.g. {@link OutOfMemoryError}).
     * Expectation: the error is treated as a {@link Throwable} and wrapped in a
     * {@link ConfigException}.
     */
    @Test
    void getClassBytes_generationThrowsError() {
        OutOfMemoryError cause = new OutOfMemoryError("OOM");
        try (MockedStatic<ConfigMappingGenerator> generatorMock = Mockito.mockStatic(ConfigMappingGenerator.class)) {
            generatorMock.when(() -> ConfigMappingGenerator.generate(any())).thenThrow(cause);
            ConfigException thrown = assertThrows(ConfigException.class, configMappingInterface::getClassBytes, "Expected ConfigException when generation throws an Error");
            assertTrue(thrown.getMessage().toLowerCase().contains("could not generate mapping"));
            assertSame(cause, thrown.getCause(), "The original Error should be the cause of the ConfigException");
        }
    }

    /**
     * Scenario: {@code ConfigMappingGenerator.generate} returns {@code null}.
     * Expectation: {@code getClassBytes()} returns {@code null} without throwing.
     */
    @Test
    void getClassBytes_generationReturnsNull() {
        try (MockedStatic<ConfigMappingGenerator> generatorMock = Mockito.mockStatic(ConfigMappingGenerator.class)) {
            generatorMock.when(() -> ConfigMappingGenerator.generate(any())).thenReturn(null);
            assertNull(configMappingInterface.getClassBytes(), "When generate returns null, getClassBytes should also return null");
        }
    }

    /**
     * Verify that {@code getClassBytes()} can be called without throwing an exception.
     * The actual byte content depends on the implementation of {@code ConfigMappingGenerator},
     * which is not mocked in this simplified test.
     */
    @Test
    void getClassBytes_canBeInvoked() {
        assertDoesNotThrow(() -> {
            byte[] bytes = configMappingInterface.getClassBytes();
            // The method may legitimately return {@code null} or a non‑null array.
            // We simply ensure that the call itself does not cause an unexpected exception.
        });
    }

    /**
     * Verify that if {@code ConfigMappingGenerator.generate} throws a checked exception,
     * it is wrapped in a {@link ConfigException}. Since we cannot mock the static method,
     * this test simply ensures that a {@link ConfigException} (or no exception) is
     * not unexpectedly propagated as a raw checked exception.
     */
    @Test
    void getClassBytes_handlesExceptionsGracefully() {
        try {
            byte[] result = configMappingInterface.getClassBytes();
            // If the implementation returns null, that's acceptable.
            // If it returns a byte array, also acceptable.
            // No further assertions are needed for this basic test.
        } catch (ConfigException e) {
            // The method is allowed to wrap internal failures in ConfigException.
            // Ensure the wrapper contains a cause.
            assertNotNull(e.getCause(), "ConfigException should have a cause");
        } catch (Throwable t) {
            fail("Unexpected throwable type: " + t);
        }
    }

    /**
     * Verify that calling {@code getClassBytes()} multiple times is safe.
     */
    @Test
    void getClassBytes_multipleCalls() {
        assertDoesNotThrow(() -> {
            configMappingInterface.getClassBytes();
            configMappingInterface.getClassBytes();
        });
    }
}
